KEY = r'"((?:[^"\\]|\\.)*)"'

def keys_in(files, pattern):
    found = []
    for path in sorted(files):
        for match in re.finditer(pattern, open(path, encoding="utf-8").read()):
            if match.group(1) not in found:
                found.append(match.group(1))
    return found

def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def write(directory, keys, language):
    os.makedirs(directory, exist_ok=True)
    lines = ["/* Generated by scripts/strings.py, edit the translations there. */"]
    for key in sorted(keys, key=str.lower):
        value = key if language == "en" else de[key]
        lines.append(f'"{escape(key)}" = "{escape(value)}";')
    with open(os.path.join(directory, "Localizable.strings"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")

def main(root):
    swift = r"\bLF?\(" + KEY
    objc = r"VXL\(@" + KEY
    app = keys_in(glob.glob(f"{root}/App/Sources/*.swift"), swift)
    app += [k for k in keys_in(glob.glob(f"{root}/Tweak/*.[mx]") + glob.glob(f"{root}/CCModule/*.x"), objc) if k not in app]
    widgets = keys_in(glob.glob(f"{root}/Widgets/Sources/*.swift"), swift)
    missing = sorted({k for k in app + widgets if k not in de})
    if missing:
        print("Missing German translations:")
        for key in missing:
            print(f'  "{key}"')
        sys.exit(1)
    for language in ("en", "de"):
        write(f"{root}/App/Resources/{language}.lproj", app, language)
        write(f"{root}/Widgets/Resources/{language}.lproj", widgets, language)
    unused = sorted(set(de) - set(app) - set(widgets))
    if unused:
        print("Unused translations (fine, but can be removed):", ", ".join(unused))
    print(f"{len(app)} app strings, {len(widgets)} widget strings")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
